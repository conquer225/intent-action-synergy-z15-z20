"""Create offline instrumental demo assets; distinct tracks, never live EEG synthesis."""
import argparse,hashlib,json,wave
from pathlib import Path
import numpy as np
RATE=48000
NOTES={'calm':([60,64,67,64,62,65,69,65],76),'steady':([60,62,64,67,65,64,62,60],94),'bright':([72,76,79,76,74,77,81,79],118)}
def prepare(out):
 out.mkdir(parents=True,exist_ok=True);tracks={}
 for genre,(notes,bpm) in NOTES.items():
  seconds=48;audio=np.zeros((RATE*seconds,2));beat=60./bpm
  for k,start in enumerate(np.arange(0,seconds,beat)):
   count=min(int(beat*RATE),len(audio)-int(start*RATE));t=np.arange(count)/RATE
   f=440*2**((notes[k%len(notes)]-69)/12);envelope=(1-np.exp(-t*45))*np.exp(-t*3/beat)
   melody=(np.sin(2*np.pi*f*t)+.23*np.sin(4*np.pi*f*t)+.1*np.sin(6*np.pi*f*t))*envelope*.14
   bass=np.sin(2*np.pi*(f/4)*t)*np.exp(-t*5/beat)*.09
   at=int(start*RATE);audio[at:at+count,0]+=melody+bass;audio[at:at+count,1]+=melody*.9+bass
   if genre=='bright':audio[at:at+count]+=((np.sin(2*np.pi*90*t)*np.exp(-t*45))*.045)[:,None]
  gain=np.minimum(np.arange(len(audio))/RATE,(len(audio)-1-np.arange(len(audio)))/RATE);gain=np.clip(gain,0,1)
  pcm=np.clip(audio*gain[:,None]*32767,-32768,32767).astype('<i2');p=out/(genre+'.wav')
  with wave.open(str(p),'wb') as w:w.setparams((2,2,RATE,0,'NONE',''));w.writeframes(pcm.tobytes())
  tracks[genre]=dict(path=p.name,title={'calm':'静水 · 舒缓','steady':'步行 · 平稳','bright':'晨光 · 明快'}[genre],sha256=hashlib.sha256(p.read_bytes()).hexdigest(),seconds=seconds,bpm=bpm)
 catalog=dict(version=1,tracks=tracks,license='CC0-1.0',source='Offline demo instrumentals generated by prepare_signal_music.py; AI-assisted composition, no borrowed melody or recording',source_sha256=hashlib.sha256(Path(__file__).read_bytes()).hexdigest())
 (out/'catalog.json').write_text(json.dumps(catalog,ensure_ascii=False,indent=2)+'\n',encoding='utf-8');print('THREE_MUSIC_TRACKS_READY')
if __name__=='__main__':
 p=argparse.ArgumentParser();p.add_argument('--output',type=Path,required=True);a=p.parse_args();prepare(a.output)
