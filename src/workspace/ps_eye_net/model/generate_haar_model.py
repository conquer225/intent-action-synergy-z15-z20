"""Offline conversion: supported, non-tilted stump cascades only. No runtime XML."""
import hashlib
import struct
import xml.etree.ElementTree as ET
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
def f(v):
    v = struct.unpack('<f', struct.pack('<f', float(v)))[0]
    s = format(v, '.9g')
    return s + ('.0' if '.' not in s and 'e' not in s else '') + 'f'
def convert(name, symbol):
    source = ROOT / 'model' / name
    c = ET.parse(source).getroot().find('cascade')
    assert c.findtext('featureType') == 'HAAR'
    width, height = int(c.findtext('width')), int(c.findtext('height'))
    features, stages, stumps = [], [], []
    for feature in c.find('features'):
        assert int(feature.findtext('tilted', '0')) == 0
        rects = []
        for r in feature.find('rects'):
            x,y,w,h,weight = r.text.split()
            x,y,w,h = map(int,(x,y,w,h))
            assert x >= 0 and y >= 0 and w > 0 and h > 0
            assert x+w <= width and y+h <= height
            rects.append('{%d,%d,%d,%d,%s}'%(x,y,w,h,f(weight)))
        assert 2 <= len(rects) <= 3
        count = len(rects)
        rects += ['{0,0,0,0,0.0f}'] * (3-count)
        features.append('{{%s},%d}'%(','.join(rects),count))
    for stage in c.find('stages'):
        first = len(stumps)
        for weak in stage.find('weakClassifiers'):
            n = weak.findtext('internalNodes').split()
            leaves = weak.findtext('leafValues').split()
            assert len(n)==4 and n[:2]==['0','-1'] and len(leaves)==2
            assert 0 <= int(n[2]) < len(features)
            stumps.append('{%s,%s,%s,%s}'%(n[2],f(n[3]),f(leaves[0]),f(leaves[1])))
        stages.append('{%d,%d,%s}'%(first,len(stumps)-first,f(float(stage.findtext('stageThreshold'))-1e-5)))
    out = ['/* Generated by model/generate_haar_model.py. See model/LICENSE.txt. */',
           '/* XML SHA256: '+hashlib.sha256(source.read_bytes()).hexdigest()+' */']
    for typ, suffix, rows in [('HaarFeature','features',features),('HaarStage','stages',stages),('HaarStump','stumps',stumps)]:
        out.append('static const %s %s_%s[] = {\n%s\n};'%(typ,symbol,suffix,',\n'.join(rows)))
    out.append('static const HaarModel %s = {%d,%d,%d,%s_features,%s_stages,%s_stumps};\n'%(symbol,width,height,len(stages),symbol,symbol,symbol))
    (ROOT/'src/app'/f'{symbol}.inc').write_text('\n'.join(out),encoding='utf-8')
    print(symbol, 'features',len(features),'stumps',len(stumps),'stages',len(stages))
if __name__=='__main__':
    convert('haarcascade_frontalface_default.xml','face_model')
    convert('haarcascade_eye.xml','eye_model')
    convert('haarcascade_frontalface_alt.xml','face_alt_model')
