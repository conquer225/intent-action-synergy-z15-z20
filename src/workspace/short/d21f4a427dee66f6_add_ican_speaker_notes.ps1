New-Item -ItemType Directory -Force -Path $outputDir | Out-Null
Copy-Item -LiteralPath $source -Destination $output -Force

$app = New-Object -ComObject PowerPoint.Application
try {
    $pres = $app.Presentations.Open($output, $false, $false, $false)
    if ($pres.Slides.Count -ne $notes.Count) {
        throw "Slide count $($pres.Slides.Count) does not match notes count $($notes.Count)"
    }
    for ($i = 1; $i -le $pres.Slides.Count; $i++) {
        $body = $null
        foreach ($shape in $pres.Slides.Item($i).NotesPage.Shapes) {
            if ($shape.Type -eq 14 -and $shape.PlaceholderFormat.Type -eq 2) {
                $body = $shape
                break
            }
        }
        if ($null -eq $body) {
            throw "No notes body placeholder on slide $i"
        }
        $body.TextFrame.TextRange.Text = $notes[$i - 1].Trim()
        $body.TextFrame.TextRange.Font.Name = 'Microsoft YaHei'
        $body.TextFrame.TextRange.Font.Size = 13
    }
    $pres.Save()
    $pres.Close()
}
finally {
    $app.Quit()
}

